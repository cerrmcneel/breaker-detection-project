def main():
    # 1. Transform small pin image sizes to /originals/ for maximum resolution
    high_res_urls = []
    for url in new_urls:
        # replace '/236x/', '/474x/', '/60x60/' etc. with '/originals/'
        high_res = re.sub(r'/(?:236x|474x|60x60|564x|736x)/', '/originals/', url)
        high_res_urls.append(high_res)
        
    # Deduplicate
    high_res_urls = list(dict.fromkeys(high_res_urls))
    
    # 2. Load existing scraped_urls.json
    db_file = "data/scraped_urls.json"
    try:
        with open(db_file, "r", encoding="utf-8") as f:
            db = json.load(f)
    except Exception:
        db = {}
        
    # 3. Add to key
    key = "pinterest_cuadro_electrico_vivienda"
    db[key] = high_res_urls
    
    # 4. Save back
    with open(db_file, "w", encoding="utf-8") as f:
        json.dump(db, f, indent=2, ensure_ascii=False)
        
    print(f"Successfully processed {len(high_res_urls)} Pinterest URLs and saved them under key '{key}' in '{db_file}'.")

if __name__ == "__main__":
    main()
